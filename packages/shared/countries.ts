const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function countryByCode(code: string | undefined | null): CountryRef | undefined {
  if (!code) return undefined;
  return BY_CODE.get(code.toUpperCase());
}

export function countryName(code: string | undefined | null): string {
  if (!code) return "Unknown location";
  return BY_CODE.get(code.toUpperCase())?.name ?? code.toUpperCase();
}

/** Regional-indicator emoji flag from an ISO-2 code ("FR" -> 🇫🇷). */
export function flagEmoji(code: string | undefined | null): string {
  if (!code || !/^[A-Za-z]{2}$/.test(code)) return "";
  return String.fromCodePoint(
    ...[...code.toUpperCase()].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65),
  );
}
